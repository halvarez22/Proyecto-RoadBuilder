function setLang(lang){
  const dict = i18n[lang] || i18n.es;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    if(dict[key]) el.textContent = dict[key];
  });
  const toggle = document.getElementById("langToggle");
  if(toggle){
    toggle.textContent = lang === "es" ? "EN" : "ES";
    toggle.setAttribute("aria-label", lang === "es" ? "Switch language" : "Cambiar idioma");
  }
  document.documentElement.lang = lang;
  localStorage.setItem("sx_lang", lang);
}

document.addEventListener("DOMContentLoaded", ()=>{
  const saved = localStorage.getItem("sx_lang") || "es";
  setLang(saved);
  const toggle = document.getElementById("langToggle");
  if(toggle){
    toggle.addEventListener("click", ()=>{
      const next = (document.documentElement.lang || "es") === "es" ? "en" : "es";
      setLang(next);
    });
  }
  const form = document.getElementById("form");
  const status = document.getElementById("formStatus");
  if(form){
    form.addEventListener("submit", (e)=>{
      e.preventDefault();
      const name = document.getElementById("name");
      const email = document.getElementById("email");
      const phone = document.getElementById("phone");
      const message = document.getElementById("message");
      const errors = [];
      if(!name.value || name.value.trim().length < 2) errors.push("Nombre inválido");
      const emailOk = /^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/.test(email.value);
      if(!emailOk) errors.push("Correo inválido");
      if(phone.value && !/^[0-9+\\-\\s()]{7,}$/.test(phone.value)) errors.push("Teléfono inválido");
      if(!message.value || message.value.trim().length < 10) errors.push("Mensaje demasiado corto");
      if(errors.length){
        status.textContent = errors.join(" · ");
        status.style.color = "#b00020";
        return;
      }
      status.textContent = document.documentElement.lang === "es" ? "Gracias, nos pondremos en contacto pronto." : "Thanks, we will contact you soon.";
      status.style.color = "#127c39";
      form.reset();
    });
  }
});
